"""Context-window management for the built-in agent.

Tool output is already truncated by the tools, and full command output lives in
files. This module handles the remaining risk: a long multi-step task slowly
filling the model window. It keeps the original task, the most recent work, and
replaces older turns with a compact summary generated by the same model.
"""

from __future__ import annotations

import json
from typing import Any

from cairn.agent.messages import Message, message_text_for_estimate, system_message, user_message
from cairn.agent.providers import BaseClient
from cairn.agent.settings import AgentSettings

COMPACT_KEEP_RECENT_TOKENS = 20000
SUMMARY_MAX_CHARS = 40_000


def compact_trigger_tokens(settings: AgentSettings) -> int:
    """Compact when the transcript reaches 80% of the model context window."""
    return max(1, int(settings.context_window * 0.8))


def estimate_text_tokens(text: str) -> int:
    if not text:
        return 0
    # Conservative for mixed English/JSON/Chinese. Tool output is mostly ASCII,
    # but Chinese graph descriptions can be ~1.5 chars/token, so use 2.
    return max(1, len(text) // 2)


def estimate_message_tokens(message: Message) -> int:
    return estimate_text_tokens(message_text_for_estimate(message)) + 6


def estimate_messages_tokens(messages: list[Message]) -> int:
    return sum(estimate_message_tokens(message) for message in messages)


def should_compact(messages: list[Message], settings: AgentSettings, *, last_prompt_tokens: int = 0) -> bool:
    estimated = estimate_messages_tokens(messages)
    tokens = max(estimated, last_prompt_tokens)
    return tokens > compact_trigger_tokens(settings)


def _segments(messages: list[Message]) -> list[list[Message]]:
    """Split a transcript into turns at user messages.

    A segment always starts with a user message and may contain the assistant
    reply plus its tool results. Keeping a segment whole prevents orphan tool
    messages, which providers reject.
    """
    segments: list[list[Message]] = []
    current: list[Message] = []
    for message in messages:
        if message.get("role") == "user" and current:
            segments.append(current)
            current = []
        current.append(message)
    if current:
        segments.append(current)
    return segments


def _format_for_summary(messages: list[Message]) -> str:
    lines: list[str] = []
    used = 0
    for message in reversed(messages):
        role = message.get("role")
        text = str(message.get("content") or "")
        tool_calls = message.get("tool_calls") or []
        if tool_calls:
            names = ", ".join(str(call.get("name")) for call in tool_calls)
            text = f"{text}\n[tool calls: {names}]".strip()
        line = f"[{role}] {text}"
        if used + len(line) > SUMMARY_MAX_CHARS:
            lines.append(f"[{len(messages) - len(lines)} earlier messages omitted from summary input]")
            break
        lines.append(line)
        used += len(line)
    lines.reverse()
    return "\n\n".join(lines)


SUMMARY_SYSTEM = """The messages above are a conversation to summarize. Create a structured context checkpoint
summary that another LLM will use to continue the work.

Use this exact format:

## Goal
[What is the user trying to accomplish? Can be multiple items.]

## Constraints & Preferences
- [Constraints, preferences, or requirements]
- [Or "(none)" if none were mentioned]

## Progress
### Done
- [x] [Completed tasks/changes]

### In Progress
- [ ] [Current work]

### Blocked
- [Issues preventing progress, if any]

## Key Decisions
- **[Decision]**: [Brief rationale]

## Next Steps
1. [Ordered list of what should happen next]

## Critical Context
- [Data, examples, references, exact paths, credentials, flags, hashes, errors needed to continue]
- [Or "(none)" if not applicable]

Keep each section concise. Preserve exact file paths, function names, command output that matters,
and error messages. Do not invent facts."""


def _summarize(client: BaseClient, settings: AgentSettings, messages: list[Message]) -> str | None:
    body = _format_for_summary(messages)
    if not body.strip():
        return None
    try:
        response = client.chat(
            [system_message(SUMMARY_SYSTEM), user_message(body)],
            [],
            max_tokens=min(4096, settings.max_tokens),
            temperature=0.0,
            timeout=min(settings.request_timeout, 180),
        )
    except Exception:
        return None
    text = response.text.strip()
    return text or None


def compact_messages(
    messages: list[Message],
    client: BaseClient,
    settings: AgentSettings,
    *,
    notice_only: bool = False,
) -> list[Message]:
    """Return a compacted copy of ``messages``.

    ``notice_only`` skips the summarization model call (used when the provider
    just reported a context-overflow error and a normal request is already the
    recovery path).
    """
    system = [message for message in messages if message.get("role") == "system"]
    conversation = [message for message in messages if message.get("role") != "system"]
    if not conversation:
        return messages

    first_user = conversation[0] if conversation[0].get("role") == "user" else None
    rest = conversation[1:] if first_user is not None else conversation
    segments = _segments(rest)
    if len(segments) < 2:
        return messages

    target_tokens = max(4096, min(COMPACT_KEEP_RECENT_TOKENS, int(settings.context_window * 0.45)))
    keep: list[list[Message]] = []
    used = estimate_messages_tokens(system) + (estimate_message_tokens(first_user) if first_user else 0)
    for segment in reversed(segments):
        cost = estimate_messages_tokens(segment)
        if keep and used + cost > target_tokens:
            break
        keep.append(segment)
        used += cost
    keep.reverse()
    older = segments[: len(segments) - len(keep)]
    if not older:
        return messages

    old_messages = [message for segment in older for message in segment]
    summary = None if notice_only else _summarize(client, settings, old_messages)
    if summary:
        replacement = user_message(
            "[Context summary of earlier work. This replaces older turns; use it to continue.]\n\n" + summary
        )
    else:
        replacement = user_message(
            f"[Earlier context omitted: {len(old_messages)} messages from {len(older)} earlier turns. "
            "Re-read files or command output files if exact details are needed.]"
        )

    compacted: list[Message] = [*system]
    if first_user is not None:
        compacted.append(
            user_message(str(first_user.get("content") or "") + "\n\n" + str(replacement.get("content") or ""))
        )
    else:
        compacted.append(replacement)
    for segment in keep:
        compacted.extend(segment)

    # Hard fallback: if the summary itself was huge or keep still exceeds the
    # budget, drop the oldest kept segments (never the last one).
    trigger_tokens = compact_trigger_tokens(settings)
    while estimate_messages_tokens(compacted) > trigger_tokens and len(keep) > 1:
        keep.pop(0)
        compacted = [*system]
        if first_user is not None:
            compacted.append(
                user_message(str(first_user.get("content") or "") + "\n\n" + str(replacement.get("content") or ""))
            )
        else:
            compacted.append(replacement)
        for segment in keep:
            compacted.extend(segment)
    return compacted


def render_messages(messages: list[Message]) -> str:
    return json.dumps(messages, ensure_ascii=False, indent=2)
